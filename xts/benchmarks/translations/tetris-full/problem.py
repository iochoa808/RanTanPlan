"""
Tetris-full XTS — companion model covering all three piece types
(one_square, two_straight, right_l) on a generic 4x4 board, not a
translation of the shipped minimal instance (see
xts/benchmarks/translations/tetris-sequential-optimal/ for that).

Reverse-engineered finding: every piece -- including right_l -- only ever
performs a rigid-body slide by one cell; the L-tromino's orientation (`lor`)
is fixed at init and never written by any action. two_straight is the one
piece that genuinely corner-turns, since its move only requires the new
cell be adjacent to the current front cell, not to continue the piece's
own axis.

Actions are generated by the same loops used to generate the PDDL in
xts/benchmarks/translations/tetris-full/domain.pddl, rather than hand-listed --
24 near-identical schemas (4 one_square + 4 two_straight + 16 right_l:
4 orientations x 4 directions) would otherwise be pure copy-paste.

two_straight needs an extra fluent-free disequality guard per direction:
IPAR grounds its 4 independent same-typed parameters (r1,c1,r2,c2)
before any fluent precondition is known, so without the guard it also
instantiates the (unreachable) "reversing into its own tail" binding,
where the back-cell-clear effect and the new-front-cell-occupy effect
target the same board address with conflicting values.

Init: square0 at (0,0); domino0 back (0,2) front (0,3); ell0 orientation 1
(right+down arms) corner (2,0). Goal: board[3][3] = 1.
Plan: slide-two-down x3 (domino0 alone reaches (3,3); satisficing, so the
square and L piece are left untouched) -- 3 steps.
"""
import sys, os
sys.path.insert(0, os.path.expanduser("~/unified-planning"))
from unified_planning.shortcuts import *

MAXI = 3
MAXJ = 3

ORIENTS = {
    0: [(-1, 0), (0, 1)],   # up, right
    1: [(0, 1), (1, 0)],    # right, down
    2: [(1, 0), (0, -1)],   # down, left
    3: [(0, -1), (-1, 0)],  # left, up
}
DIRS = {
    'up':    (-1, 0),
    'down':  (1, 0),
    'left':  (0, -1),
    'right': (0, 1),
}


def off(var, d):
    if d == 0:
        return var
    if d > 0:
        return Plus(var, Int(d))
    return Minus(var, Int(-d))


def guards(offsets, rvar, cvar):
    terms = []
    seen = set()
    for dr, dc in offsets:
        if dr < 0 and ('r', 'ge', -dr) not in seen:
            seen.add(('r', 'ge', -dr))
            terms.append(GE(rvar, Int(-dr)))
        if dr > 0 and ('r', 'le', dr) not in seen:
            seen.add(('r', 'le', dr))
            terms.append(LE(rvar, Int(MAXI - dr)))
        if dc < 0 and ('c', 'ge', -dc) not in seen:
            seen.add(('c', 'ge', -dc))
            terms.append(GE(cvar, Int(-dc)))
        if dc > 0 and ('c', 'le', dc) not in seen:
            seen.add(('c', 'le', dc))
            terms.append(LE(cvar, Int(MAXJ - dc)))
    return terms


def get_problem():
    p = Problem('tetris-xts-full')

    OneSquare   = UserType('one_square')
    TwoStraight = UserType('two_straight')
    RightL      = UserType('right_l')

    size_t   = IntType(0, 3)
    cell_t   = IntType(0, 1)
    orient_t = IntType(0, 3)

    board = Fluent('board', ArrayType(4, ArrayType(4, cell_t)))
    srow  = Fluent('srow',  size_t, e=OneSquare)
    scol  = Fluent('scol',  size_t, e=OneSquare)
    drow1 = Fluent('drow1', size_t, e=TwoStraight)
    dcol1 = Fluent('dcol1', size_t, e=TwoStraight)
    drow2 = Fluent('drow2', size_t, e=TwoStraight)
    dcol2 = Fluent('dcol2', size_t, e=TwoStraight)
    lrow  = Fluent('lrow',  size_t, e=RightL)
    lcol  = Fluent('lcol',  size_t, e=RightL)
    lor   = Fluent('lor',   orient_t, e=RightL)

    p.add_fluent(board)
    p.add_fluent(srow)
    p.add_fluent(scol)
    p.add_fluent(drow1)
    p.add_fluent(dcol1)
    p.add_fluent(drow2)
    p.add_fluent(dcol2)
    p.add_fluent(lrow)
    p.add_fluent(lcol)
    p.add_fluent(lor)

    square0 = Object('square0', OneSquare)
    domino0 = Object('domino0', TwoStraight)
    ell0    = Object('ell0', RightL)
    p.add_objects([square0, domino0, ell0])

    # square0 (0,0); domino0 back(0,2) front(0,3); ell0 corner(2,0) orient 1
    # (right+down arms) -> footprint (2,0),(2,1),(3,0)
    p.set_initial_value(board, [[1, 0, 1, 1],
                                 [0, 0, 0, 0],
                                 [1, 1, 0, 0],
                                 [1, 0, 0, 0]])
    p.set_initial_value(srow(square0), Int(0))
    p.set_initial_value(scol(square0), Int(0))
    p.set_initial_value(drow1(domino0), Int(0))
    p.set_initial_value(dcol1(domino0), Int(2))
    p.set_initial_value(drow2(domino0), Int(0))
    p.set_initial_value(dcol2(domino0), Int(3))
    p.set_initial_value(lrow(ell0), Int(2))
    p.set_initial_value(lcol(ell0), Int(0))
    p.set_initial_value(lor(ell0), Int(1))

    # ---- one_square: 4 slide actions ----
    for dname, d in DIRS.items():
        a = InstantaneousAction(f'slide-square-{dname}', e=OneSquare, r=size_t, c=size_t)
        e, r, c = a.parameter('e'), a.parameter('r'), a.parameter('c')
        a.add_precondition(Equals(srow(e), r))
        a.add_precondition(Equals(scol(e), c))
        for g in guards([d], r, c):
            a.add_precondition(g)
        new_r, new_c = off(r, d[0]), off(c, d[1])
        a.add_precondition(Equals(board[new_r][new_c], Int(0)))
        a.add_effect(board[r][c], Int(0))
        a.add_effect(board[new_r][new_c], Int(1))
        a.add_effect(srow(e), new_r)
        a.add_effect(scol(e), new_c)
        p.add_action(a)

    # ---- two_straight: 4 slide actions, front (r2,c2) leads ----
    for dname, d in DIRS.items():
        a = InstantaneousAction(f'slide-two-{dname}', e=TwoStraight,
                                 r1=size_t, c1=size_t, r2=size_t, c2=size_t)
        e, r1, c1, r2, c2 = (a.parameter('e'), a.parameter('r1'), a.parameter('c1'),
                              a.parameter('r2'), a.parameter('c2'))
        a.add_precondition(Equals(drow1(e), r1))
        a.add_precondition(Equals(dcol1(e), c1))
        a.add_precondition(Equals(drow2(e), r2))
        a.add_precondition(Equals(dcol2(e), c2))
        for g in guards([d], r2, c2):
            a.add_precondition(g)
        new_r, new_c = off(r2, d[0]), off(c2, d[1])
        # IPAR grounds r1,c1,r2,c2 independently, so it also instantiates the
        # unreachable "reversing into its own tail" binding (r1,c1)==(new_r,new_c);
        # exclude it with a fluent-free guard rather than relying on the
        # state-dependent (clear) check below.
        a.add_precondition(Not(And(Equals(r1, new_r), Equals(c1, new_c))))
        a.add_precondition(Equals(board[new_r][new_c], Int(0)))
        a.add_effect(board[r1][c1], Int(0))
        a.add_effect(board[new_r][new_c], Int(1))
        a.add_effect(drow1(e), r2)
        a.add_effect(dcol1(e), c2)
        a.add_effect(drow2(e), new_r)
        a.add_effect(dcol2(e), new_c)
        p.add_action(a)

    # ---- right_l: 16 slide actions (4 fixed orientations x 4 directions) ----
    for o, arms in ORIENTS.items():
        corner = (0, 0)
        shape = [corner] + arms
        for dname, d in DIRS.items():
            new_shape = [(dr + d[0], dc + d[1]) for (dr, dc) in shape]
            old_set, new_set = set(shape), set(new_shape)
            to_clear = [pt for pt in shape if pt not in new_set]
            to_write = [pt for pt in new_shape if pt not in old_set]

            a = InstantaneousAction(f'slide-l-o{o}-{dname}', e=RightL, r=size_t, c=size_t)
            e, r, c = a.parameter('e'), a.parameter('r'), a.parameter('c')
            a.add_precondition(Equals(lor(e), Int(o)))
            a.add_precondition(Equals(lrow(e), r))
            a.add_precondition(Equals(lcol(e), c))
            for g in guards(to_write + [d], r, c):
                a.add_precondition(g)
            for (dr, dc) in to_write:
                a.add_precondition(Equals(board[off(r, dr)][off(c, dc)], Int(0)))
            for (dr, dc) in to_clear:
                a.add_effect(board[off(r, dr)][off(c, dc)], Int(0))
            for (dr, dc) in to_write:
                a.add_effect(board[off(r, dr)][off(c, dc)], Int(1))
            a.add_effect(lrow(e), off(r, d[0]))
            a.add_effect(lcol(e), off(c, d[1]))
            p.add_action(a)

    # Goal: reach (3,3) -- domino0 alone satisfies this via 3x slide-two-down
    p.add_goal(Equals(board[Int(3)][Int(3)], Int(1)))

    return p