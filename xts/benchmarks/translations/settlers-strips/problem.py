"""
Settlers-Strips XTS — simple-civ-v2.
Features: bounded ints, object fluent (vehicle-at), set fluents (land/rail/sea-conns).
Plan: build-cabin village / build-quarry port / fell-timber / build-cart /
      move-cart / break-stone  ~5 steps.
"""
import sys, os
sys.path.insert(0, os.path.expanduser("~/unified-planning"))
from unified_planning.shortcuts import *


def get_problem():
    p = Problem('simple-civ-v2-xts')

    Store    = UserType('store')
    Place    = UserType('place',   father=Store)
    Vehicle  = UserType('vehicle', father=Store)
    Resource = UserType('resource')

    res_t    = IntType(0, 10)
    cnt_t    = IntType(0, 30)
    hse_t    = IntType(0, 10)
    PlaceSet = SetType(Place)

    # Domain constants
    timber  = Object('timber',  Resource)
    wood    = Object('wood',    Resource)
    coal    = Object('coal',    Resource)
    stone   = Object('stone',   Resource)
    iron    = Object('iron',    Resource)
    ore     = Object('ore',     Resource)
    nowhere = Object('nowhere', Place)

    # Problem objects
    village = Object('village', Place)
    port    = Object('port',    Place)
    cart1   = Object('cart1',   Vehicle)

    p.add_objects([timber, wood, coal, stone, iron, ore,
                   nowhere, village, port, cart1])

    # Fluents
    available    = Fluent('available',    res_t,    r=Resource, s=Store)
    space_in     = Fluent('space-in',     res_t,    v=Vehicle)
    labour       = Fluent('labour',       cnt_t)
    resource_use = Fluent('resource-use', cnt_t)
    pollution    = Fluent('pollution',    cnt_t)
    housing      = Fluent('housing',      hse_t,    p=Place)
    vehicle_at   = Fluent('vehicle-at',   Place,    v=Vehicle)
    land_conns   = Fluent('land-conns',   PlaceSet, p=Place)
    rail_conns   = Fluent('rail-conns',   PlaceSet, p=Place)
    sea_conns    = Fluent('sea-conns',    PlaceSet, p=Place)

    woodland      = Fluent('woodland',       p=Place)
    mountain      = Fluent('mountain',       p=Place)
    metalliferous = Fluent('metalliferous',  p=Place)
    by_coast      = Fluent('by-coast',       p=Place)
    has_cabin     = Fluent('has-cabin',      p=Place)
    has_coal_stack= Fluent('has-coal-stack', p=Place)
    has_quarry    = Fluent('has-quarry',     p=Place)
    has_mine      = Fluent('has-mine',       p=Place)
    has_sawmill   = Fluent('has-sawmill',    p=Place)
    has_ironworks = Fluent('has-ironworks',  p=Place)
    has_docks     = Fluent('has-docks',      p=Place)
    has_wharf     = Fluent('has-wharf',      p=Place)
    is_cart       = Fluent('is-cart',        v=Vehicle)
    is_train      = Fluent('is-train',       v=Vehicle)
    is_ship       = Fluent('is-ship',        v=Vehicle)
    potential_v   = Fluent('potential',      v=Vehicle)

    p.add_fluent(available,     default_initial_value=Int(0))
    p.add_fluent(space_in,      default_initial_value=Int(0))
    p.add_fluent(labour,        default_initial_value=Int(0))
    p.add_fluent(resource_use,  default_initial_value=Int(0))
    p.add_fluent(pollution,     default_initial_value=Int(0))
    p.add_fluent(housing,       default_initial_value=Int(0))
    p.add_fluent(vehicle_at,    default_initial_value=nowhere)
    p.add_fluent(land_conns,    default_initial_value=set())
    p.add_fluent(rail_conns,    default_initial_value=set())
    p.add_fluent(sea_conns,     default_initial_value=set())
    p.add_fluent(woodland,      default_initial_value=False)
    p.add_fluent(mountain,      default_initial_value=False)
    p.add_fluent(metalliferous, default_initial_value=False)
    p.add_fluent(by_coast,      default_initial_value=False)
    p.add_fluent(has_cabin,     default_initial_value=False)
    p.add_fluent(has_coal_stack,default_initial_value=False)
    p.add_fluent(has_quarry,    default_initial_value=False)
    p.add_fluent(has_mine,      default_initial_value=False)
    p.add_fluent(has_sawmill,   default_initial_value=False)
    p.add_fluent(has_ironworks, default_initial_value=False)
    p.add_fluent(has_docks,     default_initial_value=False)
    p.add_fluent(has_wharf,     default_initial_value=False)
    p.add_fluent(is_cart,       default_initial_value=False)
    p.add_fluent(is_train,      default_initial_value=False)
    p.add_fluent(is_ship,       default_initial_value=False)
    p.add_fluent(potential_v,   default_initial_value=False)

    # Init — geography
    p.set_initial_value(woodland(village),     True)
    p.set_initial_value(mountain(port),        True)
    p.set_initial_value(by_coast(port),        True)

    # Connectivity
    p.set_initial_value(land_conns(village), {port})
    p.set_initial_value(land_conns(port),    {village})
    p.set_initial_value(rail_conns(village), set())
    p.set_initial_value(rail_conns(port),    set())
    p.set_initial_value(sea_conns(village),  set())
    p.set_initial_value(sea_conns(port),     set())
    p.set_initial_value(land_conns(nowhere), set())
    p.set_initial_value(rail_conns(nowhere), set())
    p.set_initial_value(sea_conns(nowhere),  set())

    # Resources at village
    p.set_initial_value(available(timber, village), Int(3))
    p.set_initial_value(available(wood,   village), Int(0))
    p.set_initial_value(available(coal,   village), Int(0))
    p.set_initial_value(available(stone,  village), Int(0))
    p.set_initial_value(available(iron,   village), Int(0))
    p.set_initial_value(available(ore,    village), Int(0))

    # Resources at port
    for r in [timber, wood, coal, stone, iron, ore]:
        p.set_initial_value(available(r, port), Int(0))

    # Nowhere sentinel
    for r in [timber, wood, coal, stone, iron, ore]:
        p.set_initial_value(available(r, nowhere), Int(0))
    p.set_initial_value(housing(nowhere), Int(0))

    # Vehicle cart1
    p.set_initial_value(potential_v(cart1),           True)
    p.set_initial_value(vehicle_at(cart1),            nowhere)
    p.set_initial_value(space_in(cart1),              Int(0))
    for r in [timber, wood, coal, stone, iron, ore]:
        p.set_initial_value(available(r, cart1), Int(0))

    # Global counters
    p.set_initial_value(labour,           Int(0))
    p.set_initial_value(resource_use,     Int(0))
    p.set_initial_value(pollution,        Int(0))
    p.set_initial_value(housing(village), Int(0))
    p.set_initial_value(housing(port),    Int(0))

    # ---- Actions ----

    load = InstantaneousAction('load', v=Vehicle, pl=Place, r=Resource)
    v_p, pl_p, r_p = load.parameter('v'), load.parameter('pl'), load.parameter('r')
    load.add_precondition(Equals(vehicle_at(v_p), pl_p))
    load.add_precondition(GT(available(r_p, pl_p), Int(0)))
    load.add_precondition(GT(space_in(v_p), Int(0)))
    load.add_effect(space_in(v_p),        Minus(space_in(v_p), Int(1)))
    load.add_effect(available(r_p, v_p),  Plus(available(r_p, v_p), Int(1)))
    load.add_effect(available(r_p, pl_p), Minus(available(r_p, pl_p), Int(1)))
    load.add_effect(labour,               Plus(labour, Int(1)))
    p.add_action(load)

    unload = InstantaneousAction('unload', v=Vehicle, pl=Place, r=Resource)
    v_p, pl_p, r_p = unload.parameter('v'), unload.parameter('pl'), unload.parameter('r')
    unload.add_precondition(Equals(vehicle_at(v_p), pl_p))
    unload.add_precondition(GT(available(r_p, v_p), Int(0)))
    unload.add_effect(space_in(v_p),        Plus(space_in(v_p), Int(1)))
    unload.add_effect(available(r_p, v_p),  Minus(available(r_p, v_p), Int(1)))
    unload.add_effect(available(r_p, pl_p), Plus(available(r_p, pl_p), Int(1)))
    unload.add_effect(labour,               Plus(labour, Int(1)))
    p.add_action(unload)

    move_cart = InstantaneousAction('move-cart', v=Vehicle, src=Place, dst=Place)
    v_p, src_p, dst_p = [move_cart.parameter(x) for x in ('v', 'src', 'dst')]
    move_cart.add_precondition(is_cart(v_p))
    move_cart.add_precondition(SetMember(dst_p, land_conns(src_p)))
    move_cart.add_precondition(Equals(vehicle_at(v_p), src_p))
    move_cart.add_effect(vehicle_at(v_p), dst_p)
    move_cart.add_effect(labour, Plus(labour, Int(2)))
    p.add_action(move_cart)

    move_train = InstantaneousAction('move-train', v=Vehicle, src=Place, dst=Place)
    v_p, src_p, dst_p = [move_train.parameter(x) for x in ('v', 'src', 'dst')]
    move_train.add_precondition(is_train(v_p))
    move_train.add_precondition(SetMember(dst_p, rail_conns(src_p)))
    move_train.add_precondition(Equals(vehicle_at(v_p), src_p))
    move_train.add_precondition(GE(available(coal, v_p), Int(1)))
    move_train.add_effect(vehicle_at(v_p),     dst_p)
    move_train.add_effect(available(coal, v_p), Minus(available(coal, v_p), Int(1)))
    move_train.add_effect(pollution,            Plus(pollution, Int(1)))
    p.add_action(move_train)

    move_ship = InstantaneousAction('move-ship', v=Vehicle, src=Place, dst=Place)
    v_p, src_p, dst_p = [move_ship.parameter(x) for x in ('v', 'src', 'dst')]
    move_ship.add_precondition(is_ship(v_p))
    move_ship.add_precondition(SetMember(dst_p, sea_conns(src_p)))
    move_ship.add_precondition(Equals(vehicle_at(v_p), src_p))
    move_ship.add_precondition(GE(available(coal, v_p), Int(2)))
    move_ship.add_effect(vehicle_at(v_p),     dst_p)
    move_ship.add_effect(available(coal, v_p), Minus(available(coal, v_p), Int(2)))
    move_ship.add_effect(pollution,            Plus(pollution, Int(2)))
    p.add_action(move_ship)

    build_cabin = InstantaneousAction('build-cabin', pl=Place)
    pl_p = build_cabin.parameter('pl')
    build_cabin.add_precondition(woodland(pl_p))
    build_cabin.add_effect(labour, Plus(labour, Int(1)))
    build_cabin.add_effect(has_cabin(pl_p), True)
    p.add_action(build_cabin)

    build_quarry = InstantaneousAction('build-quarry', pl=Place)
    pl_p = build_quarry.parameter('pl')
    build_quarry.add_precondition(mountain(pl_p))
    build_quarry.add_effect(labour, Plus(labour, Int(2)))
    build_quarry.add_effect(has_quarry(pl_p), True)
    p.add_action(build_quarry)

    build_coal_stack = InstantaneousAction('build-coal-stack', pl=Place)
    pl_p = build_coal_stack.parameter('pl')
    build_coal_stack.add_precondition(GE(available(timber, pl_p), Int(1)))
    build_coal_stack.add_effect(labour, Plus(labour, Int(2)))
    build_coal_stack.add_effect(available(timber, pl_p), Minus(available(timber, pl_p), Int(1)))
    build_coal_stack.add_effect(has_coal_stack(pl_p), True)
    p.add_action(build_coal_stack)

    build_sawmill = InstantaneousAction('build-sawmill', pl=Place)
    pl_p = build_sawmill.parameter('pl')
    build_sawmill.add_precondition(GE(available(timber, pl_p), Int(2)))
    build_sawmill.add_effect(labour, Plus(labour, Int(2)))
    build_sawmill.add_effect(available(timber, pl_p), Minus(available(timber, pl_p), Int(2)))
    build_sawmill.add_effect(has_sawmill(pl_p), True)
    p.add_action(build_sawmill)

    build_mine = InstantaneousAction('build-mine', pl=Place)
    pl_p = build_mine.parameter('pl')
    build_mine.add_precondition(metalliferous(pl_p))
    build_mine.add_precondition(GE(available(wood, pl_p), Int(2)))
    build_mine.add_effect(labour, Plus(labour, Int(3)))
    build_mine.add_effect(available(wood, pl_p), Minus(available(wood, pl_p), Int(2)))
    build_mine.add_effect(has_mine(pl_p), True)
    p.add_action(build_mine)

    build_ironworks = InstantaneousAction('build-ironworks', pl=Place)
    pl_p = build_ironworks.parameter('pl')
    build_ironworks.add_precondition(GE(available(stone, pl_p), Int(2)))
    build_ironworks.add_precondition(GE(available(wood,  pl_p), Int(2)))
    build_ironworks.add_effect(labour, Plus(labour, Int(3)))
    build_ironworks.add_effect(available(stone, pl_p), Minus(available(stone, pl_p), Int(2)))
    build_ironworks.add_effect(available(wood,  pl_p), Minus(available(wood,  pl_p), Int(2)))
    build_ironworks.add_effect(has_ironworks(pl_p), True)
    p.add_action(build_ironworks)

    build_docks = InstantaneousAction('build-docks', pl=Place)
    pl_p = build_docks.parameter('pl')
    build_docks.add_precondition(by_coast(pl_p))
    build_docks.add_precondition(GE(available(stone, pl_p), Int(2)))
    build_docks.add_precondition(GE(available(wood,  pl_p), Int(2)))
    build_docks.add_effect(available(stone, pl_p), Minus(available(stone, pl_p), Int(2)))
    build_docks.add_effect(available(wood,  pl_p), Minus(available(wood,  pl_p), Int(2)))
    build_docks.add_effect(labour, Plus(labour, Int(2)))
    build_docks.add_effect(has_docks(pl_p), True)
    p.add_action(build_docks)

    build_wharf = InstantaneousAction('build-wharf', pl=Place)
    pl_p = build_wharf.parameter('pl')
    build_wharf.add_precondition(has_docks(pl_p))
    build_wharf.add_precondition(GE(available(stone, pl_p), Int(2)))
    build_wharf.add_precondition(GE(available(iron,  pl_p), Int(2)))
    build_wharf.add_effect(available(stone, pl_p), Minus(available(stone, pl_p), Int(2)))
    build_wharf.add_effect(available(iron,  pl_p), Minus(available(iron,  pl_p), Int(2)))
    build_wharf.add_effect(labour, Plus(labour, Int(2)))
    build_wharf.add_effect(has_wharf(pl_p), True)
    p.add_action(build_wharf)

    build_rail = InstantaneousAction('build-rail', src=Place, dst=Place)
    src_p, dst_p = build_rail.parameter('src'), build_rail.parameter('dst')
    build_rail.add_precondition(SetMember(dst_p, land_conns(src_p)))
    build_rail.add_precondition(GE(available(wood, src_p), Int(1)))
    build_rail.add_precondition(GE(available(iron, src_p), Int(1)))
    build_rail.add_effect(available(wood, src_p), Minus(available(wood, src_p), Int(1)))
    build_rail.add_effect(available(iron, src_p), Minus(available(iron, src_p), Int(1)))
    build_rail.add_effect(labour, Plus(labour, Int(2)))
    build_rail.add_effect(rail_conns(src_p), SetAdd(dst_p, rail_conns(src_p)))
    p.add_action(build_rail)

    build_house = InstantaneousAction('build-house', pl=Place)
    pl_p = build_house.parameter('pl')
    build_house.add_precondition(GE(available(wood,  pl_p), Int(1)))
    build_house.add_precondition(GE(available(stone, pl_p), Int(1)))
    build_house.add_effect(housing(pl_p),         Plus(housing(pl_p), Int(1)))
    build_house.add_effect(available(wood,  pl_p), Minus(available(wood,  pl_p), Int(1)))
    build_house.add_effect(available(stone, pl_p), Minus(available(stone, pl_p), Int(1)))
    p.add_action(build_house)

    build_cart = InstantaneousAction('build-cart', pl=Place, v=Vehicle)
    pl_p, v_p = build_cart.parameter('pl'), build_cart.parameter('v')
    build_cart.add_precondition(GE(available(timber, pl_p), Int(1)))
    build_cart.add_precondition(potential_v(v_p))
    build_cart.add_effect(available(timber, pl_p), Minus(available(timber, pl_p), Int(1)))
    build_cart.add_effect(vehicle_at(v_p),  pl_p)
    build_cart.add_effect(is_cart(v_p),     True)
    build_cart.add_effect(potential_v(v_p), False)
    build_cart.add_effect(space_in(v_p),    Int(1))
    for r in [timber, wood, coal, stone, iron, ore]:
        build_cart.add_effect(available(r, v_p), Int(0))
    build_cart.add_effect(labour, Plus(labour, Int(1)))
    p.add_action(build_cart)

    build_train = InstantaneousAction('build-train', pl=Place, v=Vehicle)
    pl_p, v_p = build_train.parameter('pl'), build_train.parameter('v')
    build_train.add_precondition(potential_v(v_p))
    build_train.add_precondition(GE(available(iron, pl_p), Int(2)))
    build_train.add_effect(available(iron, pl_p), Minus(available(iron, pl_p), Int(2)))
    build_train.add_effect(vehicle_at(v_p),  pl_p)
    build_train.add_effect(is_train(v_p),    True)
    build_train.add_effect(potential_v(v_p), False)
    build_train.add_effect(space_in(v_p),    Int(5))
    for r in [timber, wood, coal, stone, iron, ore]:
        build_train.add_effect(available(r, v_p), Int(0))
    build_train.add_effect(labour, Plus(labour, Int(2)))
    p.add_action(build_train)

    build_ship = InstantaneousAction('build-ship', pl=Place, v=Vehicle)
    pl_p, v_p = build_ship.parameter('pl'), build_ship.parameter('v')
    build_ship.add_precondition(potential_v(v_p))
    build_ship.add_precondition(GE(available(iron, pl_p), Int(4)))
    build_ship.add_effect(has_wharf(pl_p), True)
    build_ship.add_effect(available(iron, pl_p), Minus(available(iron, pl_p), Int(4)))
    build_ship.add_effect(vehicle_at(v_p),  pl_p)
    build_ship.add_effect(is_ship(v_p),     True)
    build_ship.add_effect(potential_v(v_p), False)
    build_ship.add_effect(space_in(v_p),    Int(10))
    for r in [timber, wood, coal, stone, iron, ore]:
        build_ship.add_effect(available(r, v_p), Int(0))
    build_ship.add_effect(labour, Plus(labour, Int(3)))
    p.add_action(build_ship)

    fell_timber = InstantaneousAction('fell-timber', pl=Place)
    pl_p = fell_timber.parameter('pl')
    fell_timber.add_precondition(has_cabin(pl_p))
    fell_timber.add_effect(available(timber, pl_p), Plus(available(timber, pl_p), Int(1)))
    fell_timber.add_effect(labour, Plus(labour, Int(1)))
    p.add_action(fell_timber)

    break_stone = InstantaneousAction('break-stone', pl=Place)
    pl_p = break_stone.parameter('pl')
    break_stone.add_precondition(has_quarry(pl_p))
    break_stone.add_effect(available(stone, pl_p), Plus(available(stone, pl_p), Int(1)))
    break_stone.add_effect(labour,       Plus(labour, Int(1)))
    break_stone.add_effect(resource_use, Plus(resource_use, Int(1)))
    p.add_action(break_stone)

    mine_ore = InstantaneousAction('mine-ore', pl=Place)
    pl_p = mine_ore.parameter('pl')
    mine_ore.add_precondition(has_mine(pl_p))
    mine_ore.add_effect(available(ore, pl_p), Plus(available(ore, pl_p), Int(1)))
    mine_ore.add_effect(resource_use, Plus(resource_use, Int(2)))
    p.add_action(mine_ore)

    burn_coal = InstantaneousAction('burn-coal', pl=Place)
    pl_p = burn_coal.parameter('pl')
    burn_coal.add_precondition(has_coal_stack(pl_p))
    burn_coal.add_precondition(GE(available(timber, pl_p), Int(1)))
    burn_coal.add_effect(available(timber, pl_p), Minus(available(timber, pl_p), Int(1)))
    burn_coal.add_effect(available(coal,   pl_p), Plus(available(coal,   pl_p), Int(1)))
    burn_coal.add_effect(pollution, Plus(pollution, Int(1)))
    p.add_action(burn_coal)

    saw_wood = InstantaneousAction('saw-wood', pl=Place)
    pl_p = saw_wood.parameter('pl')
    saw_wood.add_precondition(has_sawmill(pl_p))
    saw_wood.add_precondition(GE(available(timber, pl_p), Int(1)))
    saw_wood.add_effect(available(timber, pl_p), Minus(available(timber, pl_p), Int(1)))
    saw_wood.add_effect(available(wood,   pl_p), Plus(available(wood,   pl_p), Int(1)))
    p.add_action(saw_wood)

    make_iron = InstantaneousAction('make-iron', pl=Place)
    pl_p = make_iron.parameter('pl')
    make_iron.add_precondition(has_ironworks(pl_p))
    make_iron.add_precondition(GE(available(ore,  pl_p), Int(1)))
    make_iron.add_precondition(GE(available(coal, pl_p), Int(2)))
    make_iron.add_effect(available(ore,  pl_p), Minus(available(ore,  pl_p), Int(1)))
    make_iron.add_effect(available(coal, pl_p), Minus(available(coal, pl_p), Int(2)))
    make_iron.add_effect(available(iron, pl_p), Plus(available(iron,  pl_p), Int(1)))
    make_iron.add_effect(pollution, Plus(pollution, Int(2)))
    p.add_action(make_iron)

    # Goals
    p.add_goal(has_cabin(village))
    p.add_goal(has_quarry(port))
    p.add_goal(GT(available(timber, village), Int(0)))
    p.add_goal(GT(available(stone,  port),    Int(0)))
    p.add_goal(is_cart(cart1))
    p.add_goal(Equals(vehicle_at(cart1), port))

    return p
